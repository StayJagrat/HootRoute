"""Regenerate demo_places.json from the live engine: plans a route, asks /api/agents/place/suggest and writes the suggested places.

    python discover_places.py "Powell St BART" "Civic Center BART" 4 1420
"""
import asyncio
import json
import sys

from common import HERE, Engine


async def main():
    o_name, d_name = (sys.argv[1], sys.argv[2]) if len(sys.argv) > 2 else ("Powell St BART", "Civic Center BART")
    day, minute = (int(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) > 4 else (4, 1420)
    e = Engine(); lm = {l["name"]: l for l in await e.landmarks()}; o, d = lm[o_name], lm[d_name]
    await e.route("discover", (o["lat"], o["lon"]), (d["lat"], d["lon"]), day, minute)
    sug = await e.suggest("discover"); print(json.dumps(sug, indent=1)); await e.reset("discover")
    places = [dict(place_id=s["id"], name=s["name"], cat=s["cat"], seed_env=f"PLACE_AGENT_{i + 1}_SEED", port=8011 + i, open_until=minute + 80, simulated=True) for i, s in enumerate(sug[:3])]
    (HERE / "demo_places.json").write_text(json.dumps(dict(_comment="SIMULATED shop agents. Regenerated by discover_places.py from /api/agents/place/suggest.", places=places), indent=2))
    print("wrote demo_places.json")

asyncio.run(main())
